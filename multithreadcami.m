function [cami_xy,cami_yx,mutual_info,diridx,te_xy,te_yx,pointwise,confidence]...
    = multithreadcami(cause,effect,L_past,L_fut,cause_part,effect_part,tau,units,varargin)
% MULTITHREADCAMI Calculates the Causal Mutual Information (CaMI), Mutual Information,
% Transfer Entropy, Directionality Index and Pointwise Information Measures 
% when many parallel experiments are provided
%--------------------------------------------------------
% Inputs:
%           cause,effect:  the time-series. Rows are values along time (no
%                  timestamp) and columns are each experiment.
%                  E.g., experiment 3 produced a cause and an effect. The 
%                  time-series of the cause is stored in column cause[:,3]
%                  and the associated effect on column effect[:,3].
%           L_past,L_fut: length of the symbolic sequence for analysis.
%                  (e.g.: L_past=3 L_fut=2: the analysis considers if 
%                   a historic of 3 points in the variables x and y is
%                   causally related to 2 points of the future of y).
%           cause_part,effect_part: vectors defining the position where the partition
%                  division lines are located. 
%                  (e.g.: x_part=[0.5,1] means that points of x<0.5 are 
%                  symbolic encoded as '0', between 0.5 and 1 are encoded 
%                  as '1', and x>1 are encoded as '2')
%           tau: time-delay of the time-Poincare mapping. If time-series is 
%                  already generated by a map, the user should set tau to 1. 
%                  Otherwise, for "continuous time-series" the user should find
%                  the tau leading to minimisation of cross correlation, or 
%                  maximal of mutual information or maximal of CaMI. This 
%                  strategy seeks to create a time-Poincare mapping that will 
%                  behave as a Markov system by the partition chosen (lx,ly).
%           units: 'bits' (or 'bit') for log in base 2, 'nats' (or 'nat')
%                  for log in base e.
%           varargin: options:
%               'save': to save the outputs to a file.
%               'delay', followed by value (integer): to add a delay between x and y.
%                        (e.g. delay,7: gives a delay of 7 time-series
%                        points between x and y, i.e., evaluates if x causes
%                        y considering that y might have delayed response of
%                        7 time units. Value can be negative too, for studies of
%                        phenomena similar to anticipated synchronization)
%               'local', followed by value (positive integer): to calulate measures 
%                        over a sliding rectangular window
%                        (e.g. 'local',10000: gives the measures calculated 
%                        over a sliding window of 10000 points)
%               'confidence', followed by N (positive integer): estimate
%                        confidence margins as the largest CaMI, mutual
%                        information and transfer entropy X->Y over N runs
%                        with the time order of the cause shuffled within
%                        each experiment (not available with 'local')
%               'step', followed by value (positive integer): with 'local', move
%                        the window by this many points (default 1)
%               'parallel', followed by true/false: compute the 'local'
%                        windows in parallel with parfor (default true;
%                        runs serially without the Parallel Computing
%                        Toolbox and in GNU Octave)
%--------------------------------------------------------
% Outputs:
%           cami_xy: Causal Mutual Information x -> y
%           cami_yx: Causal Mutual Information y -> x
%           mutual_info:      Mutual Information between x and y,
%                    calculated using symbolic sequences
%                    of length lx in variables x and y. 
%           diridx:  Directionality Index, defined as CaMI(x->y)-CaMI(y->x),
%                    positive if flow of information is x -> y
%           te_xy:   Transfer Entropy x -> y
%           te_yx:   Transfer Entropy y -> x
%           pointwise: Struct with pointwise information measures
%           confidence: with 'confidence', struct with the margins
%                    (fields cami_xy, mutual_info, te_xy, runs); else []
%
%           if 'save': 
%                  The file "calculations.mat" is generated containing
%                  all marginal and joint probabilities required for the
%                  calculation of CaMI. 
%                  The file "output.txt" is also generated containing a summary
%                  of all results.
%--------------------------------------------------------
% Examples:
%
%     (i)  Case on Bianco-Martinez, E. and Baptista, M.S. (arXiv:1612.05023):
%
%         [cami_xy,cami_yx,mi,diridx,te_xy,te_yx] = ...
%                          multithreadcami(x,y,2,3,0.5,0.5,1,'nats');
%
%           (In the paper x and y are single column time-series from coupled logistic maps, 
%            with r=4 and alpha=0.09. I suggest trying with more columns (parallel experiments),
%           and check if the causal link becomes more evident.)
%
%     (ii) A case with 3 initial divisions (not necessarily in same positions), 
%          2 points of past->2points of future, and high lag (tau=8):
%
%         [cami_xy,cami_yx,mi,diridx,te_xy,te_yx] = ...
%                           multithreadcami(x,y,2,2,[0.2,0.6],[0.2,0.8],8,'bits');
%
%--------------------------------------------------------
%(C) Dr Arthur Valencio[1,2]', Dr Norma Valencio[1,3]'' and Dr Murilo S. Baptista[1]
%[1] Institute for Complex Systems and Mathematical Biology (ICSMB), University of Aberdeen
%[2] Research, Innovation and Dissemination Center for Neuromathematics (RIDC NeuroMat)
%[3] Department of Environmental Sciences, Federal University of Sao Carlos (UFSCar)
%'Support: CNPq [206246/2014-5] and FAPESP [2018/09900-8], Brazil
%''Support: FAPESP [17/17224-0] and CNPq [310976/2017-0], Brazil
%This package is available as is, without any warranty. Use it at your own risk.
%--------------------------------------------------------
%Original: 19 June 2018
%Update: 07 July 2019
%--------------------------------------------------------
%If useful please cite
%(1) Arthur Valencio. An information-theoretical approach to identify seismic precursors and earthquake-causing variables. PhD thesis, University of Aberdeen, 2018. Available at: http://digitool.abdn.ac.uk:1801/webclient/DeliveryManager?pid=237105&custom_att_2=simple_viewer
%(2) Arthur Valencio, Norma Valencio and Murilo S. Baptista. Multithread causality: causality toolbox for systems observed through many short parallel experiments. Open source codes for Matlab. 2018. Available at: https://github.com/artvalencio/multithread-causality/


%Below is the preamble. For the important parts, go to 'main' function.
    lx=L_past;
    ly=L_past+L_fut;

    %options
    saveoutput=0;
    delay=0;
    islocal=0;
    windowsize=0;
    step=1;
    parallel=true;
    nconfidence=0;
    i=1;
    while i<=numel(varargin)
        if ~ischar(varargin{i})
            error('multithreadcami: unknown option at position %d', i);
        end
        switch lower(varargin{i})
            case 'save'
                saveoutput=1;
                i=i+1;
            case 'delay'
                delay=varargin{i+1};
                i=i+2;
            case 'local'
                islocal=1;
                windowsize=varargin{i+1};
                i=i+2;
            case 'step'
                step=varargin{i+1};
                i=i+2;
            case 'confidence'
                nconfidence=varargin{i+1};
                i=i+2;
            case 'parallel'
                parallel=logical(varargin{i+1});
                i=i+2;
            otherwise
                error('multithreadcami: unknown option "%s"', varargin{i});
        end
    end
    switch lower(units)
        case {'bit','bits'}
            units='bits';
        case {'nat','nats'}
            units='nats';
        otherwise
            error('multithreadcami: units must be ''bits'' or ''nats''');
    end

    if islocal && nconfidence>0
        error('multithreadcami: ''confidence'' is not available with ''local''');
    end
    confidence=[];

    %check input consistency
    if ~isequal(size(cause),size(effect))
        error('x and y must be of same size!')
    end
    if length(cause_part)~=length(effect_part)
        error('cause_part and effect_part must be of same size!')
    end
    ns=length(cause_part)+1; %partition resolution

    %delay: pair cause(n) with effect(n+delay)
    if delay>0
        cause=cause(1:end-delay,:);
        effect=effect(1+delay:end,:);
    elseif delay<0
        cause=cause(1-delay:end,:);
        effect=effect(1:end+delay,:);
    end

    if islocal   %Calculates for sliding window case ('local' measures (in time))
        starts=1:step:size(cause,1)-windowsize;
        nw=numel(starts);
        [cami_xy,cami_yx,mutual_info,diridx,te_xy,te_yx]=deal(zeros(1,nw));
        pointwise=cell(1,nw);
        if parallel
            workers=Inf;
        else
            workers=0;
        end
        parfor (w=1:nw, workers)
            t=starts(w);
            [cami_xy(w),cami_yx(w),mutual_info(w),diridx(w),te_xy(w),te_yx(w),pointwise{w}] = ...
                main(cause(t:t+windowsize,:),effect(t:t+windowsize,:),lx,ly,cause_part,effect_part,tau,units,ns,0);
        end
    else %Calculation over the whole time-series ('global' measures)
        disp('Calculating')
        try
            fflush(stdout);
        catch
        end
        [cami_xy,cami_yx,mutual_info,diridx,te_xy,te_yx,pointwise] = main(cause,effect,lx,ly,cause_part,effect_part,tau,units,ns,saveoutput);
        if nconfidence>0
            confidence=confidencemargins(cause,effect,lx,ly,cause_part,effect_part,tau,units,ns,nconfidence);
            if saveoutput
                printbottom(confidence);
            end
        end
        disp('done')
    end

end

function [cami_xy,cami_yx,mutual_info,diridx,te_xy,te_yx,pointwise] = main(x,y,lx,ly,xpart,ypart,tau,units,ns,saveoutput)

    nnodes=size(x,2);
    tslen=size(x,1);
    Sx=symbolize(x,xpart);
    Sy=symbolize(y,ypart);

    %Mutual information and CaMI X->Y
    [p_xp,p_yp,p_yf,p_ypf,p_xyp,p_xypf,phi_x,phi_yp,phi_yf]=getprobabilities(Sx,Sy,lx,ly,ns,tau,tslen,nnodes);
    [mutual_info,pmi]=divergence(p_xyp,p_xp*p_yp');
    [cami_xy,pcami_xy]=divergence(p_xypf,p_xp.*reshape(p_ypf,[1,size(p_ypf)]));

    %CaMI Y->X
    [ip_x,ip_yp,ip_yf,ip_ypf,ip_xyp,ip_xypf,iphi_x,iphi_yp,iphi_yf]=getprobabilities(Sy,Sx,lx,ly,ns,tau,tslen,nnodes);
    [cami_yx,pcami_yx]=divergence(ip_xypf,ip_x.*reshape(ip_ypf,[1,size(ip_ypf)]));

    %Adjusting units
    if strcmp(units,'nats')==0
        mutual_info=mutual_info/log(2);
        cami_xy=cami_xy/log(2);
        cami_yx=cami_yx/log(2);
        pmi=pmi/log(2);
        pcami_xy=pcami_xy/log(2);
        pcami_yx=pcami_yx/log(2);
    end

    %Obtaining remaining outputs
    diridx=cami_xy-cami_yx;
    te_xy=cami_xy-mutual_info;
    te_yx=cami_yx-mutual_info;

    %Generating struct of pointwise informational measures
    pointwise.pmi=pmi;
    pointwise.pcami_xy=pcami_xy;
    pointwise.pcami_yx=pcami_yx;
    pointwise.pdiridx=pcami_xy-pcami_yx;
    pointwise.pte_xy=pcami_xy-pmi;
    pointwise.pte_yx=pcami_yx-pmi;

    %print calculations to file
    if saveoutput
        timeseries=struct('x',x,'y',y,'Sx',Sx,'Sy',Sy,'phi_x',phi_x,'phi_yp',phi_yp,'phi_yf',phi_yf,...
            'inv_phi_y',iphi_x,'inv_phi_xp',iphi_yp,'inv_phi_xf',iphi_yf);
        initialparameters=struct('resolution',ns,'symbol_x_length',lx,'symbol_y_length',ly,...
            'x_partition',xpart,'y_partition',ypart,'tau',tau,'units',units);
        fid=fopen('output.txt','w');
        fprintf(fid,'CaMI calculation (multithread)\n');
        fprintf(fid,'-----------------------------------\n');
        fprintf(fid,'Selected parameters by the user:\n');
        fprintf(fid,'- Number of symbols (ns): %d\n',ns);
        fprintf(fid,'- Length of symbolic sequence in x (lx): %d\n',lx);
        fprintf(fid,'- Length of symbolic sequence in y (ly): %d\n',ly);
        fprintf(fid,'- Time delay (tau): %d\n',tau);
        fprintf(fid,'- Position of partition delimiter lines:\n');
        fprintf(fid,'* in x: %s\n',num2str(xpart(:)',5));
        fprintf(fid,'* in y: %s\n',num2str(ypart(:)',5));
        fprintf(fid,'-----------------------------------\n');
        fprintf(fid,'Output (%s):\n',units);
        fprintf(fid,'- CaMI X->Y: %.6g\n',cami_xy);
        fprintf(fid,'- CaMI Y->X: %.6g\n',cami_yx);
        fprintf(fid,'- Directionality Index (CaMI_{X->Y} - CaMI_{Y->X}): %.6g\n',diridx);
        fprintf(fid,'- Mutual Information of X and Y: %.6g\n',mutual_info);
        fprintf(fid,'- Transfer Entropy X->Y: %.6g\n',te_xy);
        fprintf(fid,'- Transfer Entropy Y->X: %.6g\n',te_yx);
        fprintf(fid,'-----------------------------------\n');
        fprintf(fid,'**Probability boxes and timeseries can be seen in calculations.mat**\n');
        fclose(fid);
        save('calculations.mat','timeseries','initialparameters','cami_xy',...
            'cami_yx','diridx','mutual_info','te_xy','te_yx','p_xp','p_yp','p_yf','p_ypf',...
            'p_xyp','p_xypf','ip_x','ip_yp','ip_yf','ip_ypf','ip_xyp','ip_xypf','-v7');
    end
end


function S=symbolize(data,part)
% Symbol i-1 is given to values in [part(i-1), part(i)); divisions must be increasing.
    if any(diff(part(:))<0)
        error('multithreadcami: partition divisions must be in increasing order');
    end
    S=zeros(size(data));
    for i=1:numel(part)
        S=S+(data>=part(i));
    end
end


function [total,terms]=divergence(p_joint,p_indep)
% sum of p_joint.*log(p_joint./p_indep) over the cells where both are positive (in nats)
    mask=(p_indep>1e-14)&(p_joint>1e-14);
    terms=zeros(size(p_joint));
    terms(mask)=p_joint(mask).*log(p_joint(mask)./p_indep(mask));
    total=sum(terms(:));
end


function [p_xp,p_yp,p_yf,p_ypf,p_xyp,p_xypf,phi_x,phi_yp,phi_yf]=getprobabilities(Sx,Sy,lx,ly,ns,tau,tslen,nnodes)
% calculates the values of phi (symbolic words) and the probabilities used for CaMI and mutual information
% At time n, the past words use the lx tau-spaced symbols before n,
% S(n-tau*lx), ..., S(n-tau), and the future word the ly-lx tau-spaced
% symbols from n on, S(n), ..., S(n+tau*(ly-lx-1)). Only times where all
% words are complete are used, and every marginal is derived from the joint
% distribution.
    lf=ly-lx;
    n=(tau*lx+1:tslen-tau*(lf-1))';
    if isempty(n)
        error('multithreadcami: time-series too short for the chosen L_past, L_fut and tau');
    end
    px=zeros(numel(n),nnodes);
    py=zeros(numel(n),nnodes);
    pf=zeros(numel(n),nnodes);
    for k=lx:-1:1
        px=px*ns+Sx(n-tau*k,:);
        py=py*ns+Sy(n-tau*k,:);
    end
    for k=0:lf-1
        pf=pf*ns+Sy(n+tau*k,:);
    end
    phi_x=NaN(tslen,nnodes);
    phi_yp=NaN(tslen,nnodes);
    phi_yf=NaN(tslen,nnodes);
    phi_x(n,:)=px;
    phi_yp(n,:)=py;
    phi_yf(n,:)=pf;
    %joint distribution of all trials and its marginals
    p_xypf=accumarray([px(:) py(:) pf(:)]+1,1,[ns^lx,ns^lx,ns^lf])/numel(px);
    p_xyp=sum(p_xypf,3);
    p_ypf=reshape(sum(p_xypf,1),ns^lx,ns^lf);
    p_xp=sum(p_xyp,2);
    p_yp=sum(p_xyp,1)';
    p_yf=sum(p_ypf,1)';
end

function confidence = confidencemargins(cause,effect,lx,ly,xpart,ypart,tau,units,ns,nruns)
% Largest CaMI, mutual information and transfer entropy X->Y obtained when the
% time order of the cause is shuffled within every experiment (nruns times).
    margins=zeros(nruns,3);
    for run=1:nruns
        shuffled=cause;
        for node=1:size(cause,2)
            shuffled(:,node)=cause(randperm(size(cause,1)),node);
        end
        [cami_xy,~,mutual_info,~,te_xy]=main(shuffled,effect,lx,ly,xpart,ypart,tau,units,ns,0);
        margins(run,:)=[cami_xy,mutual_info,te_xy];
    end
    confidence=struct('cami_xy',max(margins(:,1)),'mutual_info',max(margins(:,2)),...
        'te_xy',max(margins(:,3)),'runs',nruns);
end

